#!/usr/bin/env python3
"""Generate control alignment metrics from the exact bundled static font bytes.

OpenType OS/2.sCapHeight; legacy faces use the specification's H-outline
fallback. No font is assigned another family's metrics. SHA256 pins provenance.
"""
from pathlib import Path
import hashlib,json
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
repo=Path(__file__).resolve().parents[2];assets=repo/'app/assets/fonts';rows=[]
faces=[('Noto Sans',assets/'NotoSans-Regular.ttf'),('Noto Sans',assets/'NotoSans-Bold.ttf'),('DejaVu Sans Mono',assets/'DejaVuSansMono.ttf')]
faces += [(f'Dify CJK {region}',assets/f'cjk/NotoSansCJK{region}-{weight}.woff2') for region in ['SC','TC','HK','JP','KR'] for weight in ['Regular','Bold']]
for family,path in faces:
 f=TTFont(path);cap=getattr(f['OS/2'],'sCapHeight',0);source='OS/2.sCapHeight'
 if not cap:
  glyphs=f.getGlyphSet();pen=BoundsPen(glyphs);glyphs[f.getBestCmap()[ord('H')]].draw(pen);cap=pen.bounds[3];source='H outline (OpenType OS/2 legacy fallback)'
 xheight=getattr(f['OS/2'],'sxHeight',0)
 if not xheight:
  glyphs=f.getGlyphSet();pen=BoundsPen(glyphs);glyphs[f.getBestCmap()[ord('x')]].draw(pen);xheight=pen.bounds[3]
 rows.append({'xHeight':xheight,'family':family,'weight':f['OS/2'].usWeightClass,'unitsPerEm':f['head'].unitsPerEm,'capHeight':cap,'metricSource':source,'file':str(path.relative_to(repo)),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
(repo/'tool/fonts/metrics.json').write_text(json.dumps(rows,indent=2)+'\n')
lines=['// GENERATED by tool/fonts/build_metrics.py from the exact bundled font bytes.','// Provenance, input SHA256 and OpenType metric sources: tool/fonts/metrics.json.','// Do not adjust these values by eye.','const bundledCapHeights = <String, Map<int, double>>{']
for family in dict.fromkeys(x['family'] for x in rows):
 lines.append(f"  '{family}': {{")
 for r in rows:
  if r['family']==family:lines.append(f"    {r['weight']}: {r['capHeight']} / {r['unitsPerEm']},")
 lines.append('  },')
lines.append('};')
lines.append('const bundledXHeights = <String, Map<int, double>>{')
for family in dict.fromkeys(x['family'] for x in rows):
 lines.append(f"  '{family}': {{")
 for r in rows:
  if r['family']==family:lines.append(f"    {r['weight']}: {r['xHeight']} / {r['unitsPerEm']},")
 lines.append('  },')
lines.append('};')
(repo/'app/lib/src/design/font_metrics.g.dart').write_text('\n'.join(lines)+'\n')
print('Generated metadata for',len(rows),'exact font files')
