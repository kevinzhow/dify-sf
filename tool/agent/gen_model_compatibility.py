#!/usr/bin/env python3
"""Generate the pinned Agent UI name filter in both runtimes. Run --check in CI."""
import argparse, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
patterns = json.loads((root/'tool/agent/model_compatibility.json').read_text())['excluded_patterns']
assert len(patterns) == 37
header = '// Generated by tool/agent/gen_model_compatibility.py; source: Dify 8387590.\n'
files = {
 'app/lib/src/agents/model_compatibility.g.dart': header + "final inlineAgentExcludedModels = [\n" + ''.join("  RegExp(r'"+p+"', caseSensitive: false),\n" for p in patterns) + '];\n',
 'server/Sources/CollabRuntime/AgentModelPatterns.g.swift': header + 'enum AgentModelPatterns {\n    static let excluded = [\n' + ''.join('        #"'+p+'"#,\n' for p in patterns) + '    ]\n}\n',
}
parser = argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); parser.add_argument('--dart-only',action='store_true'); args=parser.parse_args()
for name, text in files.items():
 if args.dart_only and not name.endswith('.dart'): continue
 path=root/name
 if args.check:
  assert path.read_text() == text, 'Regenerate '+name
 else: path.write_text(text)
