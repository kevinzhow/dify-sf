"""Generate Flutter design tokens from Dify's web source (the specification).

Usage: python3 tool/gen_dify_tokens.py <dify source root> > app/lib/src/design/dify_tokens.g.dart

Reads packages/dify-ui/src/themes/light.css and web/themes/manual-light.css (colour variables, gradients), packages/dify-ui/src/styles/utilities.css
(typography utilities) and packages/dify-ui/src/styles/styles.css (shadows). Re-run when the Dify baseline moves.
"""
import re, subprocess, sys
from pathlib import Path

root = Path(sys.argv[1])
ui = root / 'packages/dify-ui/src'

def camel(name):
    parts = re.split(r'[-_]+', name)
    out = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    return ('n' + out) if out[:1].isdigit() else out

def color(value):
    v = value.strip()
    m = re.fullmatch(r'#([0-9a-fA-F]{3,8})', v)
    if m:
        h = m.group(1)
        if len(h) in (3, 4): h = ''.join(c * 2 for c in h)
        if len(h) == 6: h += 'ff'
        rgb, a = h[:6], h[6:]
        return f'Color(0x{a}{rgb})'.upper().replace('COLOR(0X', 'Color(0x')
    m = re.fullmatch(r'rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)', v)
    if m:
        r, g, b, a = m.groups()
        a = 1.0 if a is None else (float(a[:-1]) / 100 if a.endswith('%') else float(a))
        return f'Color.fromARGB({round(a * 255)}, {r}, {g}, {b})'
    return None

out = []
version = subprocess.run(['git', '-C', str(root), 'describe', '--tags'], capture_output=True, text=True).stdout.strip()
out.append('// GENERATED by tool/gen_dify_tokens.py from Dify ' + (version or '(unknown version)') + '. Do not edit.')
out.append('// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars')
out.append("import 'dart:math' as math;")
out.append("import 'dart:ui' as ui;")
out.append('')
out.append("import 'package:flutter/painting.dart';")
out.append('')

# Colours.
light = (ui / 'themes/light.css').read_text()
colors, skipped = [], []
for name, value in re.findall(r'--color-([a-z0-9-]+):\s*([^;]+);', light):
    c = color(value)
    if c is None:
        skipped.append((name, value.strip()))
    else:
        colors.append((camel(name), c, name))
out.append('/// Dify light theme colours (`--color-*` in packages/dify-ui/src/themes/light.css).')
out.append('abstract final class DifyColors {')
seen = set()
for n, c, orig in colors:
    if n in seen: continue
    seen.add(n)
    out.append(f'  /// `{orig}`')
    out.append(f'  static const {n} = {c};')
out.append('}')
out.append('')

# Typography.
util = (ui / 'styles/utilities.css').read_text()
out.append('/// Dify typography utilities (packages/dify-ui/src/styles/utilities.css). Dify uses the system font stack;')
out.append('/// `uppercase` utilities set [DifyTextStyle.uppercase] (Flutter has no text-transform).')
out.append('class DifyTextStyle {')
out.append('  const DifyTextStyle(this.style, {this.uppercase = false});')
out.append('  final TextStyle style;')
out.append('  final bool uppercase;')
out.append('}')
out.append('')
out.append('abstract final class DifyType {')
for name, body in re.findall(r'@utility\s+([a-z0-9-]+)\s*\{([^}]*)\}', util):
    size = re.search(r'font-size:\s*([\d.]+)px', body)
    weight = re.search(r'font-weight:\s*(\d+)', body)
    lh = re.search(r'line-height:\s*([\d.]+)(px)?', body)
    if not size: continue
    fs = float(size.group(1))
    args = [f'fontSize: {fs:g}']
    if weight: args.append(f'fontWeight: FontWeight.w{weight.group(1)}')
    if lh:
        h = float(lh.group(1)) / fs if lh.group(2) else float(lh.group(1))
        args.append(f'height: {h:.10g}')
        # CSS splits the leading evenly above and below the text.
        args.append('leadingDistribution: TextLeadingDistribution.even')
    # CSS letter-spacing is normal unless a utility sets it; Material's text themes set their own, which would leak in.
    args.append('letterSpacing: 0')
    upper = 'text-transform: uppercase' in body
    out.append(f'  /// `{name}`')
    out.append(f'  static const {camel(name)} = DifyTextStyle(TextStyle({", ".join(args)}){", uppercase: true" if upper else ""});')
out.append('}')
out.append('')

# Shadows.
styles = (ui / 'styles/styles.css').read_text()
def flutter_blur(css):
    # CSS blurs with sigma = blur / 2; Flutter's BoxShadow with sigma = blurRadius * 0.57735 + 0.5 (convertRadiusToSigma).
    # Emit the blurRadius that gives CSS's sigma (sigma below 0.5 can't be expressed: the smallest positive radius).
    if css <= 0: return 0
    return round(max(1e-3, (css / 2 - 0.5) / 0.57735), 4)
def shadows(value):
    items = []
    for part in re.split(r',(?![^()]*\))', value):
        p = part.strip()
        if not p or p.startswith('inset'): continue
        m = re.match(r'(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(.+)$', p)
        if not m: continue
        x, y, blur, spread, col = m.groups()
        col = col.strip()
        m2 = re.fullmatch(r'rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)', col)
        c = f'Color.fromARGB({round(float(m2.group(4)) * 255)}, {m2.group(1)}, {m2.group(2)}, {m2.group(3)})' if m2 else color(col)
        if c is None: continue
        items.append(f'BoxShadow(offset: Offset({float(x):g}, {float(y):g}), blurRadius: {flutter_blur(float(blur)):g}, spreadRadius: {float(spread):g}, color: {c})')
    return items
out.append('/// Dify shadows (`--shadow-*` in packages/dify-ui/src/styles/styles.css; inset parts left out). Blur radii are\n/// converted so Flutter blurs as much as the browser does.')
out.append('abstract final class DifyShadows {')
for name, value in re.findall(r'--shadow-([a-z0-9-]+):\s*([^;]+);', styles):
    s = shadows(value)
    if s:
        out.append(f'  static const {camel(name)} = [{", ".join(s)}];')
out.append('}')
out.append('')
# Gradients (`--color-*: linear-gradient(...)`, light.css and web/themes/manual-light.css).
by_name = {orig: c for _, c, orig in colors}
def resolve(v):
    v = v.strip()
    m = re.fullmatch(r'var\(--([a-z0-9-]+)(?:,\s*(.+))?\)', v)
    if m:
        # Only `--color-*` variables are defined; others fall back.
        name = m.group(1)
        known = by_name.get(name[6:]) if name.startswith('color-') else None
        return known or (resolve(m.group(2)) if m.group(2) else None)
    return color(v)
def split_top(text):
    # Splits at the commas outside parentheses.
    out, depth, cur = [], 0, ''
    for ch in text:
        depth += (ch == '(') - (ch == ')')
        if ch == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    return out + [cur]
def gradient(value):
    m = re.fullmatch(r'linear-gradient\((.*)\)', ' '.join(value.split()))
    if not m: return None
    parts = [p.strip() for p in split_top(m.group(1))]
    angle = 180.0
    if parts and re.fullmatch(r'-?[\d.]+deg', parts[0]):
        angle = float(parts.pop(0)[:-3])
    elif parts and parts[0].startswith('to '):
        angle = {'to top': 0, 'to right': 90, 'to bottom': 180, 'to left': 270}.get(parts.pop(0))
        if angle is None: return None
    cols, stops = [], []
    for p in parts:
        sm = re.fullmatch(r'(.+?)\s+(-?[\d.]+)%', p)
        col, stop = (sm.group(1), float(sm.group(2)) / 100) if sm else (p, None)
        c = resolve(col)
        if c is None: return None
        cols.append(c); stops.append(stop)
    if any(x is None for x in stops):
        if len(cols) < 2 or stops[0] is not None and any(x is None for x in stops): return None
        stops = [i / (len(cols) - 1) for i in range(len(cols))]
    return f'CssLinearGradient(angle: {angle:g}, colors: [{", ".join(cols)}], stops: [{", ".join(f"{x:g}" for x in stops)}])'
manual = root / 'web/themes/manual-light.css'
sources = [light] + ([manual.read_text()] if manual.exists() else [])
out.append('/// Dify gradients (`--color-*: linear-gradient(...)` in themes/light.css and web/themes/manual-light.css).')
out.append('abstract final class DifyGradients {')
gseen = set()
for text in sources:
    for name, value in re.findall(r'--color-([a-z0-9-]+):\s*([^;]+);', text):
        g = gradient(value)
        if g and camel(name) not in gseen:
            gseen.add(camel(name))
            out.append(f'  /// `{name}`')
            out.append(f'  static const {camel(name)} = {g};')
out.append('}')
out.append('')
out.append("""/// A CSS `linear-gradient`: the gradient line runs through the box's centre at [angle] (0 = up, clockwise), long
/// enough that the corners get the first and last colours.
class CssLinearGradient extends Gradient {
  const CssLinearGradient({required this.angle, required super.colors, super.stops});
  final double angle;

  @override
  Shader createShader(Rect rect, {TextDirection? textDirection}) {
    final a = angle * math.pi / 180;
    final d = Offset(math.sin(a), -math.cos(a));
    final half = ((rect.width * d.dx).abs() + (rect.height * d.dy).abs()) / 2;
    return ui.Gradient.linear(rect.center - d * half, rect.center + d * half, colors, stops);
  }

  @override
  CssLinearGradient withOpacity(double opacity) => scale(opacity);

  @override
  CssLinearGradient scale(double factor) => CssLinearGradient(
    angle: angle,
    colors: [for (final c in colors) Color.lerp(null, c, factor)!],
    stops: stops,
  );
}
""")
out.append('/// Tailwind v4 radius scale (Dify does not override it) and the editor\'s arbitrary radii.')
out.append('abstract final class DifyRadius {')
for n, v in [('xs', 2), ('sm', 4), ('md', 6), ('lg', 8), ('xl', 12), ('xxl', 16), ('xxxl', 24), ('nodeCard', 15), ('dataSourceTab', 18), ('container', 10), ('badge', 5)]:
    out.append(f'  static const {n} = {v}.0;')
out.append('}')
print('\n'.join(out))
if skipped:
    print(f'// {len(skipped)} colour variables are not plain colours (gradients or references): ' + ', '.join(n for n, _ in skipped[:20]) + (' …' if len(skipped) > 20 else ''))
