"""Copy Dify's translations (web/i18n/<language>/<namespace>.json, i18next, flat keys) as app assets.

Usage: python3 tool/gen_dify_i18n.py <dify source root> app/assets/i18n
Copies the namespaces the app uses, for every language Dify ships, and writes the language menu
(web/i18n-config/languages.ts: value, name, supported, in Dify's order) and the time zone list (web/utils/timezone.json)
as app/lib/src/i18n/dify_locales.g.dart. Re-run when the Dify baseline moves.
"""
import json, re, shutil, sys
from pathlib import Path

NAMESPACES = ['workflow', 'common', 'plugin', 'plugin-trigger', 'tools', 'app', 'app-debug', 'run-log', 'app-log', 'time',
              'agent-v-2', 'dataset', 'dataset-settings', 'dataset-creation', 'dataset-documents', 'plugin-trigger', 'pipeline',
              'share', 'explore', 'app-overview', 'login', 'permission', 'permission-keys', 'app-api', 'billing']
src, out = Path(sys.argv[1]) / 'web/i18n', Path(sys.argv[2])
if out.exists():
    shutil.rmtree(out)
langs = sorted(p.name for p in src.iterdir() if (p / 'common.json').exists())
for lang in langs:
    for ns in NAMESPACES:
        f = src / lang / f'{ns}.json'
        if f.exists():
            (out / lang).mkdir(parents=True, exist_ok=True)
            # Re-serialised compactly; content unchanged.
            (out / lang / f.name).write_text(json.dumps(json.loads(f.read_text()), ensure_ascii=False, separators=(',', ':')))
(out / 'languages.json').write_text(json.dumps(langs))
web = Path(sys.argv[1]) / 'web'
ts = (web / 'i18n-config/languages.ts').read_text()
locales = re.findall(r"value: '([^']+)',\s*name: '([^']+)',.*?supported: (true|false)", ts, re.S)
tz = json.loads((web / 'utils/timezone.json').read_text())
q = lambda v: json.dumps(v, ensure_ascii=False).replace('$', '\\$')
dart = ['// GENERATED by tool/gen_dify_i18n.py from Dify\'s web/i18n-config/languages.ts and web/utils/timezone.json.',
        '// Do not edit.', '// ignore_for_file: lines_longer_than_80_chars', '',
        "/// Dify's languages (`languages`), in its order: value, name, supported.",
        'const difyLanguages = <({String value, String name, bool supported})>[']
dart += [f'  (value: {q(v)}, name: {q(n)}, supported: {sup}),' for v, n, sup in locales]
dart += ['];', '', "/// Dify's time zones (`timezones`): value (IANA) and name.", 'const difyTimezones = <({String value, String name})>[']
dart += [f'  (value: {q(t["value"])}, name: {q(t["name"])}),' for t in tz]
dart += ['];', '']
(out.parents[1] / 'lib/src/i18n/dify_locales.g.dart').write_text('\n'.join(dart))
print(f'{len(locales)} menu languages, {len(tz)} time zones')
