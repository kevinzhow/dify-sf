/// Generates `lib/src/harness/codex/vendored.g.dart` from the verbatim
/// upstream files in `../third_party/codex/upstream/` (the Docker build
/// context is this package, so the texts are compiled in).
///
///     dart run tool/gen_codex_vendor.dart
library;

import 'dart:io';

/// Constant name → path under `third_party/codex/`.
const vendoredFiles = {
  'codexFallbackPrompt': 'upstream/codex-rs/models-manager/prompt.md',
  'codexGpt6AstraTemplate':
      'upstream/codex-rs/models-manager/gpt-6-astra.instructions_template.md',
  'codexDangerFullAccessTemplate': 'upstream/codex-rs/prompts/templates/permissions/sandbox_mode/danger_full_access.md',
  'codexApprovalNeverTemplate': 'upstream/codex-rs/prompts/templates/permissions/approval_policy/never.md',
  'codexApplyPatchLark': 'upstream/codex-rs/core/assets/tools/apply_patch.lark',
  'codexNotice': 'NOTICE',
};

const outputPath = 'lib/src/harness/codex/vendored.g.dart';

String thirdPartyCodexDir() => '${Directory.current.path}/../third_party/codex';

/// A Dart single-quoted literal of [s] (every character kept).
String dartLiteral(String s) {
  final b = StringBuffer("'");
  for (final r in s.runes) {
    switch (r) {
      case 0x5c:
        b.write(r'\\');
      case 0x27:
        b.write(r"\'");
      case 0x24:
        b.write(r'\$');
      case 0x0a:
        b.write(r'\n');
      case 0x0d:
        b.write(r'\r');
      case 0x09:
        b.write(r'\t');
      default:
        if (r < 0x20 || r == 0x7f) {
          b.write('\\u{${r.toRadixString(16)}}');
        } else {
          b.writeCharCode(r);
        }
    }
  }
  b.write("'");
  return b.toString();
}

String generateVendored([String? root]) {
  final dir = root ?? thirdPartyCodexDir();
  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_codex_vendor.dart from third_party/codex/;',
    )
    ..writeln(
      '// do not edit. The texts are OpenAI Codex rust-v0.163.0, Copyright 2025',
    )
    ..writeln(
      '// OpenAI, Apache License 2.0, verbatim (see third_party/codex/).',
    )
    ..writeln()
    ..writeln('/// Verbatim upstream texts of the `codex` harness style.')
    ..writeln('library;')
    ..writeln()
    ..writeln('// ignore_for_file: lines_longer_than_80_chars');
  for (final e in vendoredFiles.entries) {
    final text = File('$dir/${e.value}').readAsStringSync();
    b
      ..writeln()
      ..writeln('/// `${e.value}`.')
      ..writeln('const ${e.key} =')
      ..writeln('    ${dartLiteral(text)};');
  }
  return b.toString();
}

void main() {
  File(outputPath).writeAsStringSync(generateVendored());
  stdout.writeln('wrote $outputPath');
}
